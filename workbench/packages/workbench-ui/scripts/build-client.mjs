// build-client.mjs — bundle packages/workbench-ui/src/client.tsx into the
// DSH browser plugin format (window.__ModuleLoader__.load) at client.js.
//
// Strategy (mirrors how @deepseek-ai client packages ship):
//   - esbuild bundles the TSX source to a single CJS file.
//   - react / react/jsx-runtime stay EXTERNAL — the DSH shell module table
//     provides them (the official bundles require them the same way).
//   - @xyflow/react (and its CSS) are INLINED into our bundle.
//   - The CJS output is wrapped in the ModuleLoader factory, which supplies
//     `module` / `exports` / `require`.
//
// Run:  node scripts/build-client.mjs   (from packages/workbench-ui)

import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outFile = join(root, "client.js");

const result = await build({
  entryPoints: [join(root, "src", "client.tsx")],
  bundle: true,
  format: "cjs",
  platform: "browser",
  jsx: "automatic",
  target: ["es2020"],
  external: ["react", "react/jsx-runtime", "@deepseek-ai/dsh-client-ui-primitives"],
  loader: { ".css": "text" },
  write: false,
  minify: false,
  logLevel: "info",
});

const code = result.outputFiles[0].text;
const wrapper = `// GENERATED by scripts/build-client.mjs — do not edit by hand.\nwindow.__ModuleLoader__.load({\n  id: "@workflow-platform/workbench-ui",\n  factory: (require) => {\n    var module = { exports: {} };\n    var exports = module.exports;\n${code}\n    return module.exports;\n  }\n});\n`;
writeFileSync(outFile, wrapper, "utf8");
console.log(`[build-client] wrote ${outFile} (${code.length} bytes bundled)`);
